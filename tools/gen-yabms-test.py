#!/usr/bin/env python3
"""Generate lean/Test/YaBMS.lean from yaBMS (https://github.com/koteitan/yaBMS).

usage: gen-yabms-test.py BMS STATES OUT

  BMS     the yaBMS binary (c/bms)
  STATES  lines "<version> <matrix>", printed by lean/Explore/States.lean
  OUT     the Lean file to write

For every matrix and every bracket n in BRACKETS, the expansion computed by
yaBMS is written as `example : expand R M n = <yaBMS output> := by decide`.
"""
import re
import subprocess
import sys

RULE = {"1.1": "BM1_1", "2": "BM2"}
BRACKETS = [1, 2]


def bm(s):
    """'(0,0)(1,1)' -> 'bm[(0,0)(1,1)]'"""
    if not re.fullmatch(r"(\(\d+(,\d+)*\))*", s):
        raise ValueError(f"unexpected matrix: {s!r}")
    return f"bm[{s}]" if s else "([] : Mat)"


def main():
    bms, states, out = sys.argv[1:4]
    seen = set()
    lines = [
        "import Common.Rules",
        "",
        "/-!",
        "# Cross-check with yaBMS",
        "",
        "Generated by `tools/gen-yabms-test.py`.  Each example states that the",
        "expansion of this project equals the output of yaBMS",
        "(https://github.com/koteitan/yaBMS) with `-v 1.1` (BM1.1) or `-v 2` (BM2),",
        "for the matrices on the standardness paths and on the loops.",
        "-/",
        "",
        "namespace DeadBms.Test.YaBMS",
        "",
    ]
    count = 0
    for row in open(states):
        ver, mat = row.split()
        if (ver, mat) in seen:
            continue
        seen.add((ver, mat))
        for n in BRACKETS:
            res = subprocess.run([bms, "-v", ver, f"{mat}[{n}]"], capture_output=True, text=True,
                                 check=True).stdout.strip()
            lines.append(f"example : expand {RULE[ver]} {bm(mat)} {n} =")
            lines.append(f"    {bm(res)} := by decide")
            count += 1
    lines += ["", "end DeadBms.Test.YaBMS", ""]
    open(out, "w").write("\n".join(lines))
    print(f"{count} examples written to {out}")


if __name__ == "__main__":
    main()
